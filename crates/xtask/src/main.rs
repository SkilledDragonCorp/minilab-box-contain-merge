//! Lab maintenance tasks. `extract-upstream` regenerates `scripts/upstream-test.sh`
//! from `ci/upstream/rust-test-lint.yml` so local commands stay byte-faithful to upstream CI.

use std::fs;
use std::path::PathBuf;
use std::process::ExitCode;

fn main() -> ExitCode {
    let mut args = std::env::args().skip(1);
    let Some(cmd) = args.next() else {
        eprintln!("usage: cargo run -p xtask --locked -- extract-upstream");
        return ExitCode::from(2);
    };
    match cmd.as_str() {
        "extract-upstream" => {
            if let Err(error) = extract_upstream() {
                eprintln!("xtask extract-upstream: {error}");
                return ExitCode::from(1);
            }
            ExitCode::SUCCESS
        }
        other => {
            eprintln!("unknown xtask: {other}");
            ExitCode::from(2)
        }
    }
}

fn repo_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn extract_upstream() -> Result<(), String> {
    let root = repo_root();
    let yaml_path = root.join("ci/upstream/rust-test-lint.yml");
    let yaml = fs::read_to_string(&yaml_path)
        .map_err(|error| format!("read {}: {error}", yaml_path.display()))?;

    let build = extract_run_body(&yaml, "Build")?;
    let linux_tests = extract_run_body(&yaml, "Run tests (linux)")?;
    let fmt = extract_run_body(&yaml, "cargo fmt")?;
    let clippy = extract_run_body(&yaml, "cargo clippy")?;

    let mut script = String::from("#!/usr/bin/env bash\n");
    script.push_str("# GENERATED by `cargo run -p xtask --locked -- extract-upstream`.\n");
    script.push_str("# Do not edit by hand. Source: ci/upstream/rust-test-lint.yml\n");
    script.push_str("set -euo pipefail\n");
    script.push_str("ROOT=\"$(cd \"$(dirname \"${BASH_SOURCE[0]}\")/..\" && pwd)\"\n");
    script.push_str("cd \"$ROOT\"\n");
    script.push_str("export CARGO_TERM_COLOR=\"${CARGO_TERM_COLOR:-always}\"\n");
    script.push_str("export RUSTFLAGS=\"${RUSTFLAGS:--C debuginfo=0}\"\n");
    script.push_str("export FAIL_FAST_FLAG=\"${FAIL_FAST_FLAG:---no-fail-fast}\"\n");
    script.push_str("export FILTER=\"${FILTER:-}\"\n");
    script.push('\n');

    script.push_str("echo \"== upstream local: Build ==\"\n");
    script.push_str("( cd upstream\n");
    append_indented(&mut script, &build);
    script.push_str(")\n\n");

    script.push_str("echo \"== upstream local: Run tests (linux skips) ==\"\n");
    script.push_str("( cd upstream\n");
    script.push_str("  export FAIL_FAST_FLAG=\"${FAIL_FAST_FLAG:---no-fail-fast}\"\n");
    script.push_str("  export FILTER=\"${FILTER:-}\"\n");
    append_indented(&mut script, &linux_tests);
    script.push_str(")\n\n");

    script.push_str("echo \"== upstream local: cargo fmt ==\"\n");
    script.push_str("( cd upstream\n");
    append_indented(&mut script, &fmt);
    script.push_str(")\n\n");

    script.push_str("echo \"== upstream local: cargo clippy ==\"\n");
    script.push_str("( cd upstream\n");
    append_indented(&mut script, &clippy);
    script.push_str(")\n");

    let out = root.join("scripts/upstream-test.sh");
    fs::create_dir_all(out.parent().expect("scripts dir"))
        .map_err(|error| format!("mkdir scripts: {error}"))?;
    fs::write(&out, script).map_err(|error| format!("write {}: {error}", out.display()))?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let mut perms = fs::metadata(&out)
            .map_err(|error| format!("stat {}: {error}", out.display()))?
            .permissions();
        perms.set_mode(0o755);
        fs::set_permissions(&out, perms)
            .map_err(|error| format!("chmod {}: {error}", out.display()))?;
    }
    eprintln!("wrote {}", out.display());
    Ok(())
}

fn append_indented(script: &mut String, body: &str) {
    for line in body.lines() {
        script.push_str("  ");
        script.push_str(line);
        script.push('\n');
    }
}

fn extract_run_body(yaml: &str, step_name: &str) -> Result<String, String> {
    let marker = format!("- name: {step_name}");
    let start = yaml
        .find(&marker)
        .ok_or_else(|| format!("step not found: {step_name}"))?;
    let after = &yaml[start..];
    let lines: Vec<&str> = after.lines().collect();
    let mut i = 0;
    while i < lines.len() {
        let line = lines[i];
        if i > 0 && line.trim_start().starts_with("- name:") {
            break;
        }
        if line.trim_start().starts_with("run: |") {
            i += 1;
            let mut body = String::new();
            while i < lines.len() {
                let l = lines[i];
                if let Some(rest) = l.strip_prefix("          ") {
                    body.push_str(rest);
                    body.push('\n');
                    i += 1;
                    continue;
                }
                if l.trim().is_empty() {
                    body.push('\n');
                    i += 1;
                    continue;
                }
                break;
            }
            if body.trim().is_empty() {
                return Err(format!("empty run body for {step_name}"));
            }
            return Ok(body);
        }
        if let Some(rest) = line.trim_start().strip_prefix("run: ")
            && !rest.starts_with('|')
        {
            return Ok(format!("{rest}\n"));
        }
        i += 1;
    }
    Err(format!("could not parse run body for {step_name}"))
}
